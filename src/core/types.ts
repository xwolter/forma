export type RecordBase = { id: string; updatedAt: string; schemaVersion: 1 };
export type Nutrients = {
  kcal: number;
  protein: number | null;
  fat: number | null;
  carbs: number | null;
};
export type Profile = RecordBase & {
  name: string;
  height: number | null;
  age: number | null;
  goal: "reduce" | "maintain" | "build";
  days: number;
  equipmentId: string;
  theme: "dark" | "light";
  waterGoal: number | null;
  haptics: boolean;
  timerSound: boolean;
  notifications: boolean;
  notificationAsked?: boolean;
  demo: boolean;
  spotify?: string;
  keepAwake?: boolean;
};
export type Goal = RecordBase &
  Nutrients & { effectiveFrom: string; method: "manual" };
export type Equipment = RecordBase & {
  name: string;
  types: string[];
  step: number;
  notes: string;
  exerciseNotes?: Record<string, string>;
};
export type LoadType =
  "barbell" | "dumbbell" | "machine" | "bodyweight" | "assistance";
export type Exercise = {
  id: string;
  name: string;
  muscle: string;
  equipment: string;
  pattern: string;
  loadType: LoadType;
  instructions: string[];
  mistakes: string[];
  alternatives: string[];
  metric?: 'seconds' | 'distance';
  demoId?: string;
  demoViews?: boolean;
  searchTerms?: string;
  sourceId?: string;
  loadMultiplier?: 1 | 2;
  loadHint?: string;
  trainingType?: 'cardio' | 'strength';
  level?: 'beginner' | 'intermediate' | 'expert';
  lowImpact?: boolean;
  recommended?: boolean;
  defaultTarget?: {sets:number;min:number;max:number;rest:number};
};
export type PlanExercise = {
  id: string;
  exerciseId: string;
  sets: number;
  min: number;
  max: number;
  rest: number;
  warmupRest?: number;
  rir: number | null;
  notes: string;
  group?: string;
  tempo?: string;
  target?: string;
  restBetween?: number;
  weeklySets?: number[];
  metric?: 'reps' | 'seconds' | 'distance';
};
export type Plan = RecordBase & {
  name: string;
  subtitle: string;
  minutes: number;
  version: number;
  exercises: PlanExercise[];
  weekdays: number[];
  program?: string;
  programWeek?: number;
  notes?: string;
  cardio?: string;
  source?: string;
};
export type Session = RecordBase & {
  date: string;
  timezone: string;
  planId: string;
  planSnapshot: Plan;
  equipmentId: string;
  equipmentName: string;
  status: "active" | "paused" | "finished" | "abandoned";
  startedAt: number;
  endedAt: number | null;
  pausedAt: number | null;
  pausedMs: number;
  currentExercise: number;
  restEndsAt: number | null;
  note: string;
  pain: boolean;
  mood: string;
  comparable: boolean;
  lastActiveAt?: number;
  restRemaining?: number;
};
export type WorkoutSet = RecordBase & {
  sessionId: string;
  slotId: string;
  exerciseId: string;
  equipmentId: string;
  index: number;
  type: "work" | "warmup" | "assisted";
  loadType: LoadType;
  weight: number;
  reps: number;
  rir: number | null;
  done: boolean;
  skipped: boolean;
  completedAt: number | null;
  metric?: 'reps' | 'seconds' | 'distance';
  draft?: { weight: string; reps: string; rir: string };
};
export type Product = RecordBase &
  Nutrients & {
    name: string;
    brand: string;
    unit: "g" | "ml";
    barcode: string;
    favorite: boolean;
    source: string;
    sourceUrl?: string;
    imageUrl?: string;
    photoKey?: number;
    photoData?: string;
    fetchedAt?: string;
    sourceModified?: string;
    servingSize?: string;
    servingGrams?: number;
    originalName?: string;
    searchTerms?: string;
    kind?: 'basic' | 'dish' | 'packaged';
    tags?: string[];
  };
export type FoodEntry = RecordBase & {
  date: string;
  meal: string;
  name: string;
  brand: string;
  productId: string | null;
  recipeVersion: number | null;
  grams: number;
  unit: "g" | "ml" | "porcja";
  nutrients: Nutrients;
  status: "consumed" | "planned";
  quick: boolean;
};
export type RecipeIngredient = {
  productId: string;
  name: string;
  grams: number;
  unit: "g" | "ml";
  nutrients: Nutrients;
};
export type Recipe = RecordBase & {
  name: string;
  photoKey?: number;
  photoData?: string;
  version: number;
  cookedWeight: number;
  ingredients: RecipeIngredient[];
  nutrients: Nutrients;
};
export type Measurement = RecordBase & {
  date: string;
  value: number;
  note: string;
  source: "manual";
  timestamp: string;
};
export type Daily = RecordBase & {
  date: string;
  appOpened?: boolean;
  water: number;
  complete: boolean;
  energy: number | null;
  sleep: number | null;
};
export type Activity = RecordBase & {
  date: string;
  name: string;
  minutes: number;
  distance: number | null;
  kcal: number | null;
  sourceId: string | null;
};
export type Media = RecordBase & {
  exerciseId: string;
  blob: Blob;
  name: string;
  mime: string;
};
export type Tables = {
  profiles: Profile;
  goals: Goal;
  equipment: Equipment;
  plans: Plan;
  sessions: Session;
  sets: WorkoutSet;
  products: Product;
  food: FoodEntry;
  recipes: Recipe;
  measurements: Measurement;
  daily: Daily;
  activities: Activity;
};
export type TableName = keyof Tables;
export type AppData = { [K in TableName]: Tables[K][] };
export type Tab = "today" | "training" | "food" | "progress";
