function filled(I:Icon):LucideIcon{return function FilledIcon(props:IconProps){const {strokeWidth:_stroke,fill:_fill,...rest}=props;return <I {...rest} weight="fill" aria-hidden={props['aria-label']?undefined:true}/>;};}
// Arrows, carets and plus/minus use the bold outline weight, as in the FORMA 0.8 design.
function bold(I:Icon):LucideIcon{return function BoldIcon(props:IconProps){const {strokeWidth:_stroke,fill:_fill,...rest}=props;return <I {...rest} weight="bold" aria-hidden={props['aria-label']?undefined:true}/>;};}
